// Dateibibliothek: G-code, 3MF (gesliced oder Modell), STL/STEP/OBJ.
// Beim Hochladen werden Druckzeit, Filament, Druckermodell und Vorschaubild
// aus den Slicer-Metadaten gelesen – egal ob Bambu Studio, OrcaSlicer,
// PrusaSlicer, Snapmaker Orca, Anycubic Slicer Next oder Cura.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { pipeline } = require('stream/promises');
const { DATA_DIR, store } = require('./store');
const { openZip } = require('./zip');

const FILES_DIR = path.join(DATA_DIR, 'files');
fs.mkdirSync(FILES_DIR, { recursive: true });

const MAX_SIZE = 2 * 1024 ** 3; // 2 GB
const KINDS = {
  gcode: 'gcode',
  '3mf': '3mf',
  stl: 'model',
  step: 'model',
  stp: 'model',
  obj: 'model',
};

const db = store('files.json', []);

/** Dateiendung inkl. Sonderfall .gcode.3mf */
function extOf(name) {
  const lower = name.toLowerCase();
  if (lower.endsWith('.gcode.3mf')) return '3mf';
  return path.extname(lower).slice(1);
}

function safeName(name) {
  return path.basename(String(name || 'datei')).replace(/[\\/:*?"<>|\x00-\x1f]+/g, '_').slice(0, 180) || 'datei';
}

// Druckdateien liegen im Datenordner oder am eingestellten Speicherort (NAS); gesucht wird an beiden Stellen
const storage = require('./storage');
const filePath = (f) => storage.find('files', `${f.id}.${f.ext}`);
const thumbPath = (f) => storage.find('files', `${f.id}.thumb`);

// ------------------------------------------------------------------ Metadaten

function parseDuration(str) {
  if (!str) return null;
  let sec = 0;
  let found = false;
  for (const [, n, unit] of String(str).matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/gi)) {
    found = true;
    sec += Number(n) * { d: 86400, h: 3600, m: 60, s: 1 }[unit.toLowerCase()];
  }
  return found ? Math.round(sec) : null;
}

/** Wertet Kommentarzeilen aus G-code-Kopf und -Ende aus. */
function parseGcodeText(text, meta) {
  const get = (re) => {
    const m = text.match(re);
    return m ? m[1].trim() : null;
  };
  meta.slicer ??= get(/^;\s*generated by\s+(.+)$/im) || get(/^;\s*(?:FLAVOR|Generated with)\s*:?\s*(Cura[^\n]*)$/im);
  if (meta.slicer) meta.slicer = meta.slicer.replace(/\s+on\s+\d{4}-\d{2}-\d{2}.*$/, '').replace(/\s+at\s+.*$/, '');

  meta.printerModel ??=
    get(/^;\s*printer_model\s*=\s*(.+)$/im) ||
    get(/^;\s*printer_settings_id\s*=\s*(.+)$/im) ||
    get(/^;\s*MACHINE_NAME\s*:?\s*(.+)$/im) ||
    get(/^;\s*machine_name\s*=\s*(.+)$/im);

  meta.estimatedSec ??=
    parseDuration(get(/^;\s*estimated printing time(?: \(normal mode\))?\s*[=:]\s*(.+)$/im)) ||
    parseDuration(get(/^;\s*model printing time:\s*([^;]+)/im)) ||
    (get(/^;TIME:(\d+)/m) ? Number(get(/^;TIME:(\d+)/m)) : null);

  // Gesamtgewicht und – falls vorhanden – Gewicht je Filament ("1.20, 3.40" bzw. "1.2;3.4")
  const perFil = get(/^;\s*filament used \[g\]\s*=\s*([\d.,; ]+)$/im);
  if (perFil && !meta.filamentGs) {
    const list = perFil.split(/\s*[;,]\s*/).map(Number).filter((n) => !Number.isNaN(n));
    if (list.length) meta.filamentGs = list.map((n) => Math.round(n * 100) / 100);
  }
  const total = get(/^;\s*total filament (?:weight|used) \[g\]\s*[=:]\s*([\d.]+)/im);
  if (meta.filamentG == null) {
    if (total) meta.filamentG = Math.round(Number(total) * 10) / 10;
    else if (meta.filamentGs) meta.filamentG = Math.round(meta.filamentGs.reduce((a, b) => a + b, 0) * 10) / 10;
  }
  const meters = get(/^;Filament used:\s*([\d.]+)m/m);
  if (meters && meta.filamentM == null) meta.filamentM = Number(meters);

  const types = get(/^;\s*filament_type\s*=\s*(.+)$/im);
  const colors = get(/^;\s*(?:filament_colou?r|extruder_colou?r)\s*=\s*(.+)$/im);
  if (types && !meta.materials) {
    const t = types.split(';').map((s) => s.trim());
    const c = (colors || '').split(';').map((s) => s.trim());
    meta.materials = t.map((type, i) => ({ type, color: /^#[0-9a-f]{6}/i.test(c[i] || '') ? c[i].slice(0, 7) : null }));
  }
  if (meta.materials && meta.filamentGs && meta.materials.length === meta.filamentGs.length) {
    meta.materials.forEach((m, i) => (m.grams ??= meta.filamentGs[i]));
  }
  meta.layerHeight ??= num(get(/^;\s*layer_height\s*=\s*([\d.]+)/im)) || num(get(/^;Layer height:\s*([\d.]+)/m));
  meta.nozzle ??= num(get(/^;\s*nozzle_diameter\s*=\s*([\d.]+)/im));
  meta.layers ??= num(get(/^;\s*total layers? (?:count|number)\s*[=:]\s*(\d+)/im)) || num(get(/^;LAYER_COUNT:(\d+)/m));
}

const num = (v) => (v == null || v === '' || Number.isNaN(Number(v)) ? null : Number(v));

/** Größtes eingebettetes Vorschaubild (PNG/JPG, Base64-Kommentarblock). */
function extractGcodeThumb(text) {
  let best = null;
  const re = /^;\s*thumbnail(?:_(PNG|JPG|QOI))? begin (\d+)x(\d+) \d+\s*\n([\s\S]*?)^;\s*thumbnail(?:_\w+)? end/gim;
  for (const m of text.matchAll(re)) {
    if (m[1] && m[1].toUpperCase() === 'QOI') continue;
    const area = Number(m[2]) * Number(m[3]);
    if (!best || area > best.area) best = { area, b64: m[4].replace(/^;\s?/gm, '').replace(/\s+/g, '') };
  }
  return best ? Buffer.from(best.b64, 'base64') : null;
}

function readHeadTail(file, headLen = 512 * 1024, tailLen = 256 * 1024) {
  const fd = fs.openSync(file, 'r');
  try {
    const size = fs.fstatSync(fd).size;
    const head = Buffer.alloc(Math.min(size, headLen));
    fs.readSync(fd, head, 0, head.length, 0);
    let tail = Buffer.alloc(0);
    if (size > headLen) {
      tail = Buffer.alloc(Math.min(tailLen, size - headLen));
      fs.readSync(fd, tail, 0, tail.length, size - tail.length);
    }
    return { head: head.toString('utf8'), tail: tail.toString('utf8') };
  } finally {
    fs.closeSync(fd);
  }
}

function analyzeGcode(file) {
  const meta = {};
  const { head, tail } = readHeadTail(file);
  parseGcodeText(head, meta);
  parseGcodeText(tail, meta); // PrusaSlicer/Orca schreiben die Einstellungen ans Ende
  return { meta, thumb: extractGcodeThumb(head), sliced: true };
}

function xmlAttr(tag, name) {
  const m = tag.match(new RegExp(`\\b${name}="([^"]*)"`));
  return m ? m[1] : null;
}

function analyze3mf(file) {
  const zip = openZip(file);
  try {
    const meta = {};
    let thumb = null;
    const gcodeEntries = zip.entries.filter((e) => /^Metadata\/plate_\d+\.gcode$/i.test(e.name));
    meta.plates = gcodeEntries.map((e) => e.name.match(/plate_(\d+)/)[1]).map(Number).sort((a, b) => a - b);

    const info = zip.find(/^Metadata\/slice_info\.config$/i);
    if (info) {
      const xml = zip.read(info).toString('utf8');
      // je Platte: Zeit, Gewicht, Filamente (für Drucke einer anderen Platte als 1)
      const plates = (xml.match(/<plate>[\s\S]*?<\/plate>/gi) || []).map((px) => {
        const md = Object.fromEntries((px.match(/<metadata [^>]*>/g) || []).map((t) => [xmlAttr(t, 'key'), xmlAttr(t, 'value')]));
        return {
          index: num(md.index),
          estimatedSec: num(md.prediction),
          filamentG: num(md.weight),
          materials: (px.match(/<filament [^>]*\/?>/g) || []).map((t) => ({ type: xmlAttr(t, 'type'), color: xmlAttr(t, 'color') ? xmlAttr(t, 'color').slice(0, 7) : null, grams: num(xmlAttr(t, 'used_g')), slot: num(xmlAttr(t, 'id')) })),
        };
      }).filter((x) => x.index);
      if (plates.length > 1) meta.platesInfo = plates;
      const plate = (xml.match(/<plate>[\s\S]*?<\/plate>/i) || [xml])[0];
      for (const tag of plate.match(/<metadata [^>]*>/g) || []) {
        const key = xmlAttr(tag, 'key');
        const val = xmlAttr(tag, 'value');
        if (key === 'prediction') meta.estimatedSec = num(val);
        if (key === 'weight') meta.filamentG = num(val);
        if (key === 'printer_model_id') meta.printerModelId = val;
        if (key === 'nozzle_diameters') meta.nozzle = num(String(val).split(',')[0]);
      }
      const fils = (plate.match(/<filament [^>]*\/?>/g) || []).map((t) => ({
        type: xmlAttr(t, 'type'),
        color: xmlAttr(t, 'color') ? xmlAttr(t, 'color').slice(0, 7) : null,
        grams: num(xmlAttr(t, 'used_g')),
        slot: num(xmlAttr(t, 'id')),
      }));
      if (fils.length) meta.materials = fils;
    }

    const settings = zip.find(/^Metadata\/project_settings\.config$/i);
    if (settings) {
      try {
        const cfg = JSON.parse(zip.read(settings).toString('utf8'));
        meta.printerModel ??= cfg.printer_model || cfg.printer_settings_id || null;
        meta.layerHeight ??= num(cfg.layer_height);
        if (!meta.materials && Array.isArray(cfg.filament_type)) {
          meta.materials = cfg.filament_type.map((type, i) => ({ type, color: cfg.filament_colour?.[i]?.slice(0, 7) || null }));
        }
      } catch {
        /* andere Slicer: kein JSON */
      }
    }

    if (gcodeEntries.length) {
      const head = zip.read(gcodeEntries[0], 512 * 1024).toString('utf8');
      parseGcodeText(head, meta);
    }

    const png = zip.find(/^Metadata\/plate_1\.png$/i) || zip.find(/^Metadata\/thumbnail\.png$/i) || zip.find(/^Metadata\/plate_\d+\.png$/i);
    if (png) thumb = zip.read(png);
    return { meta, thumb, sliced: gcodeEntries.length > 0 };
  } finally {
    zip.close();
  }
}

function analyze(file, kind) {
  try {
    if (kind === 'gcode') return analyzeGcode(file);
    if (kind === '3mf') return analyze3mf(file);
  } catch (err) {
    return { meta: { error: err.message }, thumb: null, sliced: false };
  }
  return { meta: {}, thumb: null, sliced: false };
}

