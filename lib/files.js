/**
 * Datei aus einem Stream übernehmen.
 * @returns Dateieintrag
 */
/** Fingerabdruck einer Datei (SHA-256) – erkennt doppelte Dateien und neu geslicte Versionen */
function hashFile(file) {
  return new Promise((resolve, reject) => {
    const h = crypto.createHash('sha256');
    fs.createReadStream(file).on('data', (c) => h.update(c)).on('end', () => resolve(h.digest('hex'))).on('error', reject);
  });
}

/** Ältere Einträge ohne Fingerabdruck nachrüsten (einmalig, im Hintergrund) */
async function ensureHashes() {
  let changed = false;
  for (const f of db.data) {
    if (f.hash || !fs.existsSync(filePath(f))) continue;
    try {
      f.hash = await hashFile(filePath(f));
      changed = true;
    } catch {
      /* Datei weg */
    }
  }
  if (changed) db.save();
}
setTimeout(() => ensureHashes().catch(() => {}), 5000).unref?.();

function findByHash(hash) {
  return hash ? db.data.find((f) => f.hash === hash) || null : null;
}

/** Gleichnamige Datei mit anderem Inhalt = neu geslicte Version (Endung egal) */
const stem = (n) => String(n || '').toLowerCase().replace(/\.gcode\.3mf$|\.3mf$|\.gcode$/i, '');

/**
 * Datei aus einem Stream übernehmen.
 * dedupe: gibt es dieselbe Datei (gleicher Inhalt) schon, wird keine Kopie angelegt, sondern die vorhandene geliefert.
 * @returns Dateieintrag (bei Dublette mit existing: true)
 */
async function addFromStream(stream, originalName, { source = 'upload', note = null, demo = false, dedupe = false, extra = null } = {}) {
  const name = safeName(originalName);
  const ext = extOf(name);
  const kind = KINDS[ext];
  if (!kind) {
    stream.resume();
    throw Object.assign(new Error(`Dateityp .${ext} wird nicht unterstützt (G-code, 3MF, STL, STEP, OBJ)`), { status: 415 });
  }
  const id = crypto.randomUUID();
  const entry = { id, name, ext, kind, size: 0, source, note, uploadedAt: new Date().toISOString(), ...(demo ? { demo: true } : {}), ...(extra || {}) };
  // neue Datei: an den Speicherort, wenn erreichbar – sonst lokal (wird später nachgezogen)
  const wdir = storage.writeDir('files').dir; // legt nur den eigenen Unterordner an
  const target = path.join(wdir, `${id}.${ext}`);
  let size = 0;
  const hash = crypto.createHash('sha256');
  stream.on('data', (c) => {
    hash.update(c);
    size += c.length;
    if (size > MAX_SIZE) stream.destroy(Object.assign(new Error('Datei zu groß (max. 2 GB)'), { status: 413 }));
  });
  try {
    await pipeline(stream, fs.createWriteStream(target));
  } catch (err) {
    fs.rmSync(target, { force: true });
    throw err;
  }
  entry.size = size;
  entry.hash = hash.digest('hex');
  const same = findByHash(entry.hash);
  if (same && dedupe) {
    fs.rmSync(target, { force: true });
    return { ...same, existing: true };
  }
  // neu geslicte Version einer vorhandenen Datei? (nicht für vom Drucker übernommene Dateien)
  if (!demo && source !== 'printer') {
    const older = db.data.filter((f) => !f.demo && f.hash !== entry.hash && stem(f.name) === stem(name)).sort((a, b) => Date.parse(b.uploadedAt) - Date.parse(a.uploadedAt))[0];
    if (older) entry.replaces = older.id;
  }
  const { meta, thumb, sliced } = analyze(target, kind);
  entry.meta = meta;
  entry.printable = sliced && (kind === 'gcode' || kind === '3mf');
  if (thumb && thumb.length > 100) {
    fs.writeFileSync(path.join(wdir, `${id}.thumb`), thumb);
    entry.thumb = thumb[0] === 0xff ? 'image/jpeg' : 'image/png';
  }
  db.data.push(entry);
  db.save();
  return entry;
}

function list() {
  return db.data.slice().reverse();
}

function get(id) {
  return db.data.find((f) => f.id === id) || null;
}

function update(id, patch) {
  const f = get(id);
  if (!f) return null;
  if (patch.name) {
    const n = safeName(patch.name);
    if (extOf(n) === f.ext) f.name = n;
  }
  if (patch.note !== undefined) f.note = patch.note ? String(patch.note).slice(0, 500) : null;
  if (patch.replacesDone) delete f.replaces; // Hinweis „neue Version“ erledigt
  if (patch.keep !== undefined) f.keep = Boolean(patch.keep); // vom Drucker übernommen: nicht automatisch löschen
  db.save();
  return f;
}

function remove(id) {
  const idx = db.data.findIndex((f) => f.id === id);
  if (idx < 0) return false;
  const [f] = db.data.splice(idx, 1);
  fs.rmSync(filePath(f), { force: true });
  fs.rmSync(thumbPath(f), { force: true });
  db.save();
  return true;
}

function addFromBuffer(buf, name, opts) {
  return addFromStream(require('stream').Readable.from([buf]), name, opts);
}

function removeDemo() {
  for (const f of db.data.filter((x) => x.demo)) remove(f.id);
}

module.exports = { addFromBuffer, removeDemo, addFromStream, list, get, update, remove, filePath, thumbPath, extOf, parseDuration, hashFile, findByHash, stem };
